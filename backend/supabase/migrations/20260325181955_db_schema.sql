CREATE TABLE IF NOT EXISTS public.traders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wallet_address text NOT NULL UNIQUE,
    added_date timestamp without time zone DEFAULT now(),
    still_monitoring boolean DEFAULT true,
    trusted_score numeric(10,2) DEFAULT 0,
    statistics jsonb
);

CREATE TABLE IF NOT EXISTS public.wallet (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    capital numeric(18,2) NOT NULL DEFAULT 0,
    total numeric(18,2) NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS public.trades (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trade_name text,
    icon text,
    price numeric(18,8),
    created_at timestamp without time zone DEFAULT now(),
    trade_score integer,
    position text,
    status text,
    user_copy text,
    CONSTRAINT trades_user_copy_fkey
        FOREIGN KEY (user_copy)
        REFERENCES public.traders(wallet_address)
);